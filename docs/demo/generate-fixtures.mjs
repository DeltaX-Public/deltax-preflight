#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { preflight } from '../../src/preflight.mjs';

const demoRoot = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(demoRoot, '../..');
const outputPath = join(demoRoot, 'fixtures.js');
const source = {
  decision: 'examples/github-agent-gate/decision.json',
  policy: 'examples/github-agent-gate/policy.json',
  manifest: 'examples/github-agent-gate/manifest.json',
  evidence_producer: 'integration/derive-evidence.mjs',
  validator: 'src/preflight.mjs'
};
const readJson = async path => JSON.parse(await readFile(path, 'utf8'));

async function generateFixtures() {
  const [original, policy, manifest] = await Promise.all([
    readJson(join(repositoryRoot, source.decision)),
    readJson(join(repositoryRoot, source.policy)),
    readJson(join(repositoryRoot, source.manifest))
  ]);
  const reviewedCandidate = id => {
    const entry = manifest.candidates.find(candidate => candidate.id === id);
    if (!entry) throw new Error(`Demo requires reviewed candidate ${id}`);
    return { id: entry.id, payload: structuredClone(entry.payload) };
  };
  const changed = structuredClone(original);
  const inspection = changed.candidates.find(candidate => candidate.id === 'inspect_change');
  if (!inspection) throw new Error('Demo requires inspect_change in the starter proposal');
  inspection.payload.scope = 'public';
  const twoOptions = structuredClone(original);
  twoOptions.candidates = [reviewedCandidate('inspect_change'), reviewedCandidate('compare_evidence')];
  const publication = structuredClone(original);
  publication.candidates = [reviewedCandidate('publish_change')];

  const scenarios = [
    {
      id: 'reviewed-proposal',
      title: 'One reviewed local option',
      description: 'Inspection satisfies the example policy. Publication violates its no-external-effect rule.',
      expected_status: 'PASS_SINGLE',
      decision: original
    },
    {
      id: 'changed-payload',
      title: 'Same ID, changed payload',
      description: 'The inspection scope changes from local to public. The reviewed manifest no longer provides facts for that payload.',
      expected_status: 'EVIDENCE_REQUIRED',
      decision: changed
    },
    {
      id: 'two-valid-options',
      title: 'Two reviewed local options',
      description: 'Inspection and evidence comparison both satisfy the example policy. Selection remains open.',
      expected_status: 'SELECTION_REQUIRED',
      decision: twoOptions
    },
    {
      id: 'refused-publication',
      title: 'Only a disallowed option',
      description: 'Publication is the only proposal and violates the example policy. No candidate is admissible.',
      expected_status: 'REFUSE',
      decision: publication
    }
  ];

  const temporaryRoot = await mkdtemp(join(demoRoot, '.fixtures-work-'));
  try {
    const scenes = [];
    for (const scenario of scenarios) {
      const decisionPath = join(temporaryRoot, `${scenario.id}-decision.json`);
      const evidencePath = join(temporaryRoot, `${scenario.id}-evidence.json`);
      await writeFile(decisionPath, `${JSON.stringify(scenario.decision, null, 2)}\n`, { flag: 'wx' });
      execFileSync(process.execPath, [
        join(repositoryRoot, source.evidence_producer),
        relative(repositoryRoot, decisionPath),
        source.manifest,
        relative(repositoryRoot, evidencePath)
      ], {
        cwd: repositoryRoot,
        env: { ...process.env, GITHUB_WORKSPACE: repositoryRoot },
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'pipe']
      });
      const evidence = await readJson(evidencePath);
      const { result } = preflight(scenario.decision, policy, evidence);
      if (result.status !== scenario.expected_status) {
        throw new Error(`${scenario.id}: expected ${scenario.expected_status}, received ${result.status}`);
      }
      scenes.push({
        id: scenario.id,
        title: scenario.title,
        description: scenario.description,
        decision: scenario.decision,
        policy,
        evidence,
        result
      });
    }
    return '// Generated by docs/demo/generate-fixtures.mjs. Do not edit by hand.\n'
      + `window.PREFLIGHT_DEMO_FIXTURES = ${JSON.stringify({ schema_version: 1, source, scenes }, null, 2)};\n`;
  } finally {
    await rm(temporaryRoot, { recursive: true, force: true });
  }
}

async function main() {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
    throw new Error('Usage: node docs/demo/generate-fixtures.mjs [--check]');
  }
  const expected = await generateFixtures();
  if (args[0] === '--check') {
    let actual;
    try { actual = await readFile(outputPath, 'utf8'); }
    catch (error) { if (error.code !== 'ENOENT') throw error; }
    if (actual !== expected) {
      throw new Error('Demo fixtures are stale. Run node docs/demo/generate-fixtures.mjs');
    }
    process.stdout.write('Demo fixtures match the evidence producer and validator.\n');
  } else {
    await writeFile(outputPath, expected);
    process.stdout.write('Generated docs/demo/fixtures.js from the evidence producer and validator.\n');
  }
}

main().catch(error => {
  process.stderr.write(`${error.message}\n`);
  process.exitCode = 1;
});
